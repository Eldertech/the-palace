"""
tinyplot.py
===========

A dependency-free raster + PNG writer for this bundle. Pillow is not installed
alongside numpy on this machine, and a plot is not worth an install, so the
house contract stays "numpy + the standard library only": draw into a uint8
RGB array, encode with zlib.

Provides a 5x7 bitmap font (uppercase ASCII, digits, and the punctuation the
catalog labels use), line/rect primitives, and `write_png`.
"""
from __future__ import annotations
import struct
import zlib

import numpy as np

