def text(img, x, y, s, color, scale=2):
    """Draw uppercase 5x7 text. Unknown glyphs render as a blank cell."""
    for ch in str(s).upper():
        g = _F.get(ch, _F[" "])
        for r in range(7):
            bits = g[r]
            for c in range(5):
                if bits & (1 << (4 - c)):
                    px, py = x + c * scale, y + r * scale
                    if 0 <= py < img.shape[0] - scale and 0 <= px < img.shape[1] - scale:
                        img[py:py + scale, px:px + scale] = color
        x += 6 * scale
    return x


def line(img, p0, p1, color, width=1):
    x0, y0 = p0
    x1, y1 = p1
    n = int(max(abs(x1 - x0), abs(y1 - y0))) + 1
    xs = np.linspace(x0, x1, n).round().astype(int)
    ys = np.linspace(y0, y1, n).round().astype(int)
    h, w = img.shape[:2]
    for dx in range(width):
        for dy in range(width):
            X = np.clip(xs + dx, 0, w - 1)
            Y = np.clip(ys + dy, 0, h - 1)
            img[Y, X] = color


def polyline(img, pts, color, width=2):
    for a, b in zip(pts[:-1], pts[1:]):
        line(img, a, b, color, width)


def write_png(path, img):
    """Encode a (h, w, 3) uint8 array as a PNG."""
    h, w = img.shape[:2]
    raw = b"".join(b"\x00" + img[r].astype(np.uint8).tobytes() for r in range(h))

    def chunk(tag, data):
        c = tag + data
        return struct.pack(">I", len(data)) + c + struct.pack(">I", zlib.crc32(c) & 0xFFFFFFFF)

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(raw, 9)))
        f.write(chunk(b"IEND", b""))
